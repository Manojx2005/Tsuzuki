"""Generate the Tsuzuki Dot logo vector drawables.

Run from the repo root:  python3 tools/gen_icons.py
The logo is a bookmark ribbon drawn as a dot matrix, with three white dots ("…") down the middle.
Coordinates use a 108-unit canvas (Android adaptive icon size).
"""
import os

OUT = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res', 'drawable')
RED, WHITE, GRID = '#FFFF2D2D', '#FFFFFFFF', '#FF262626'


def circ(x, y, r):
    return f"M{x - r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0,1 1,{2 * r:.2f},0a{r:.2f},{r:.2f} 0,1 1,{-2 * r:.2f},0Z"


def in_ribbon(x, y):
    return 41 <= x <= 67 and 17 <= y <= 77 + 11 * abs(x - 54) / 14 - 2


def is_ellipsis(x, y):
    return abs(x - 54) < 4 and any(abs(y - c) < 4 for c in (36, 49, 62))


def points(scale):
    t = lambda v: (v - 54) * scale + 54
    rib, ell, bg = [], [], []
    for i in range(-8, 26):
        for j in range(-8, 26):
            x, y = 2 + 6.5 * j, 3 + 6.5 * i
            X, Y = t(x), t(y)
            if in_ribbon(x, y):
                (ell if is_ellipsis(x, y) else rib).append((X, Y))
            elif -2 <= X <= 110 and -2 <= Y <= 110:
                bg.append((X, Y))
    return rib, ell, bg


def vector(paths, size_dp=108, even_odd=False):
    body = ''.join(
        f'\n    <path\n        android:fillColor="{c}"' + ('\n        android:fillType="evenOdd"' if even_odd else '') + f'\n        android:pathData="{d}" />'
        for c, d in paths
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Tsuzuki logo. Generated by tools/gen_icons.py, do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="108"
    android:viewportHeight="108">{body}
</vector>
'''


def dots(pts, r):
    return ''.join(circ(x, y, r) for x, y in pts)


def write(name, text):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(text)


# Launcher icon (adaptive): foreground and background share one grid so the dots line up.
s = 0.85
rib, ell, bg = points(s)
write('ic_launcher_background.xml', vector([('#FF000000', 'M0,0h108v108h-108z'), (GRID, dots(bg, 0.9 * s))]))
write('ic_launcher_foreground.xml', vector([(RED, dots(rib, 2.5 * s)), (WHITE, dots(ell, 2.5 * s))]))

# Themed icon (Android 13+): one colour, the "…" dots are left out so they read as holes.
s = 0.62
rib, _, _ = points(s)
write('ic_launcher_monochrome.xml', vector([(WHITE, dots(rib, 2.5 * s))]))

# Full-colour mark for the splash screen and the About header.
rib, ell, _ = points(1)
write('ic_tsuzuki_dots.xml', vector([(RED, dots(rib, 2.5)), (WHITE, dots(ell, 2.5))], size_dp=72))

# Solid silhouette for notifications (dots are too small at 24 dp). Kept as ic_mihon so callers don't change.
ribbon = 'M44,16h20a4,4 0,0 1,4,4v70l-14,-11l-14,11V20a4,4 0,0 1,4,-4Z'
write('ic_mihon.xml', vector([(WHITE, ribbon + ''.join(circ(54, c, 4.4) for c in (36, 49, 62)))], size_dp=24, even_odd=True))
print('icons written to', os.path.normpath(OUT))
